# 8-Puzzle Configuration matching Slide 11
# 0 represents the blank/empty space

GOAL_STATE = (
    (1, 2, 3),
    (4, 5, 6),
    (7, 8, 0)
)

INITIAL_STATE = (
    (1, 2, 3),
    (0, 4, 6),
    (7, 5, 8)
)

def find_blank(state):
    """Finds the (row, col) coordinates of the blank space (0)."""
    for r in range(3):
        for c in range(3):
            if state[r][c] == 0:
                return r, c

def get_neighbors(state):
    """Generates all valid adjacent states by moving the blank tile."""
    neighbors = []
    r, c = find_blank(state)

    # Allowed moves: Up, Down, Left, Right
    moves = [(-1, 0), (1, 0), (0, -1), (0, 1)]

    for dr, dc in moves:
        nr, nc = r + dr, c + dc
        if 0 <= nr < 3 and 0 <= nc < 3:
            # Convert tuple to mutable list to swap elements
            new_state = [list(row) for row in state]
            new_state[r][c], new_state[nr][nc] = new_state[nr][nc], new_state[r][c]
            # Convert back to immutable tuple format
            neighbors.append(tuple(tuple(row) for row in new_state))

    return neighbors

def print_solution(path):
    """Utility to print the path steps in a grid format."""
    if not path:
        print("No solution found.")
        return
    print(f"Goal reached in {len(path) - 1} steps!\n")
    for step, state in enumerate(path):
        print(f"--- Step {step} ---")
        for row in state:
            print(f"| {row[0]} {row[1]} {row[2]} |")
        print()

def dfs_solve(start_state, max_depth=20):
    """Solves the 8-puzzle using Depth-First Search up to a maximum depth."""
    # Stack stores: (current_state, path_to_current)
    stack = [(start_state, [start_state])]
    visited = set()

    while stack:
        current, path = stack.pop()

        if current == GOAL_STATE:
            return path

        # Limit depth to prevent infinite paths/system crash in Colab
        if len(path) > max_depth:
            continue

        if current not in visited:
            visited.add(current)
            # Explore neighbors
            for neighbor in get_neighbors(current):
                if neighbor not in visited:
                    stack.append((neighbor, path + [neighbor]))

    return None

# Execute DFS
print("Executing Depth-First Search (DFS)...")
dfs_path = dfs_solve(INITIAL_STATE, max_depth=30)
print_solution(dfs_path)