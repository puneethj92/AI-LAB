# 8-Puzzle Configuration matching Slide 11
# 0 represents the blank/empty space

GOAL_STATE = (
    (1, 2, 3),
    (4, 5, 6),
    (7, 8, 0)
)

INITIAL_STATE = (
    (1, 2, 3),
    (0, 4, 6),
    (7, 5, 8)
)

def find_blank(state):
    """Finds the (row, col) coordinates of the blank space (0)."""
    for r in range(3):
        for c in range(3):
            if state[r][c] == 0:
                return r, c

def get_neighbors(state):
    """Generates all valid adjacent states by moving the blank tile."""
    neighbors = []
    r, c = find_blank(state)

    # Allowed moves: Up, Down, Left, Right
    moves = [(-1, 0), (1, 0), (0, -1), (0, 1)]

    for dr, dc in moves:
        nr, nc = r + dr, c + dc
        if 0 <= nr < 3 and 0 <= nc < 3:
            # Convert tuple to mutable list to swap elements
            new_state = [list(row) for row in state]
            new_state[r][c], new_state[nr][nc] = new_state[nr][nc], new_state[r][c]
            # Convert back to immutable tuple format
            neighbors.append(tuple(tuple(row) for row in new_state))

    return neighbors

def print_solution(path):
    """Utility to print the path steps in a grid format."""
    if not path:
        print("No solution found.")
        return
    print(f"Goal reached in {len(path) - 1} steps!\n")
    for step, state in enumerate(path):
        print(f"--- Step {step} ---")
        for row in state:
            print(f"| {row[0]} {row[1]} {row[2]} |")
        print()

def depth_limited_search(state, depth, path, visited):
    """Helper function performing a depth-bound DFS."""
    if state == GOAL_STATE:
        return path
    if depth <= 0:
        return None

    visited.add(state)
    for neighbor in get_neighbors(state):
        if neighbor not in visited:
            # Pass a copy of visited to keep paths isolated at this level
            result = depth_limited_search(neighbor, depth - 1, path + [neighbor], visited.copy())
            if result is not None:
                return result
    return None

def ids_solve(start_state, max_depth_limit=50):
    """Solves the 8-puzzle by incrementally increasing the DFS depth limit."""
    for depth in range(max_depth_limit):
        visited = set()
        result = depth_limited_search(start_state, depth, [start_state], visited)
        if result is not None:
            print(f"Solution found at Depth Limit: {depth}")
            return result
    return None

# Execute IDS
print("Executing Iterative Deepening Search (IDS)...")
ids_path = ids_solve(INITIAL_STATE)
print_solution(ids_path)